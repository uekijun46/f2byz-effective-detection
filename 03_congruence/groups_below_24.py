"""The 25 nonabelian groups of order less than 24, together with S_4 and
SL_2(F_3) as controls.

A group is a triple (elements, mul, e): a list of hashable elements, a binary
operation on them, and the identity. Each group is built from an explicit
construction, and `check_catalogue` confirms the order, nonabelianness, and
pairwise non-isomorphism within each order, against the classification.
"""
import os, sys
_R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [_R, os.path.join(_R, "src"), os.path.dirname(os.path.abspath(__file__))]

from itertools import product


class Group:
    def __init__(self, name, elements, mul, e):
        self.name = name
        self.elements = list(elements)
        self.mul = mul
        self.e = e
        self.index = {g: i for i, g in enumerate(self.elements)}

    def __len__(self):
        return len(self.elements)

    def order_of(self, g):
        k, x = 1, g
        while x != self.e:
            x = self.mul(x, g); k += 1
        return k

    def exponent(self):
        from math import lcm
        n = 1
        for g in self.elements:
            n = lcm(n, self.order_of(g))
        return n

    def inv(self, g):
        x = g
        while self.mul(x, g) != self.e:
            x = self.mul(x, g)
        return x

    def is_abelian(self):
        return all(self.mul(a, b) == self.mul(b, a)
                   for a in self.elements for b in self.elements)

    def closure(self, gens):
        seen = {self.e}; fr = [self.e]
        while fr:
            nx = []
            for x in fr:
                for g in gens:
                    y = self.mul(x, g)
                    if y not in seen:
                        seen.add(y); nx.append(y)
            fr = nx
        return seen


# ---------------------------------------------------------------- builders

def semidirect(n, m, act, name):
    """Z/n rtimes Z/m, where act(b) is the multiplier by which b acts on Z/n."""
    els = [(a, b) for a in range(n) for b in range(m)]
    def mul(p, q):
        return ((p[0] + act(p[1]) * q[0]) % n, (p[1] + q[1]) % m)
    return Group(name, els, mul, (0, 0))


def dihedral(n):
    return semidirect(n, 2, lambda b: 1 if b == 0 else -1, "D_%d" % n)


def dicyclic(n):
    """Dicyclic of order 4n: Z/2n rtimes Z/4 amalgamated; here as the group
    with presentation a^{2n}=1, b^2=a^n, b a b^{-1} = a^{-1}."""
    els = [(a, b) for a in range(2 * n) for b in range(2)]
    def mul(p, q):
        a1, b1 = p; a2, b2 = q
        a = a1 + (a2 if b1 == 0 else -a2)
        b = b1 + b2
        if b >= 2:
            b -= 2; a += n
        return (a % (2 * n), b)
    return Group("Dic_%d" % (4 * n), els, mul, (0, 0))


def direct(G, H, name):
    els = [(g, h) for g in G.elements for h in H.elements]
    def mul(p, q):
        return (G.mul(p[0], q[0]), H.mul(p[1], q[1]))
    return Group(name, els, mul, (G.e, H.e))


def cyclic(n):
    return Group("Z/%d" % n, list(range(n)), lambda a, b: (a + b) % n, 0)


def quaternion8():
    # units {+-1, +-i, +-j, +-k} as pairs (sign, symbol)
    sym = ['1', 'i', 'j', 'k']
    table = {('1', s): (1, s) for s in sym}
    for s in sym:
        table[(s, '1')] = (1, s)
    table[('i', 'i')] = (-1, '1'); table[('j', 'j')] = (-1, '1')
    table[('k', 'k')] = (-1, '1')
    table[('i', 'j')] = (1, 'k'); table[('j', 'k')] = (1, 'i')
    table[('k', 'i')] = (1, 'j')
    table[('j', 'i')] = (-1, 'k'); table[('k', 'j')] = (-1, 'i')
    table[('i', 'k')] = (-1, 'j')
    els = [(s, t) for s in (1, -1) for t in sym]
    def mul(p, q):
        s, t = table[(p[1], q[1])]
        return (p[0] * q[0] * s, t)
    return Group("Q_8", els, mul, (1, '1'))


def perm_group(name, gens, deg):
    """Group generated by the given permutations of {0,...,deg-1}."""
    e = tuple(range(deg))
    def mul(p, q):
        return tuple(p[q[i]] for i in range(deg))
    seen = {e}; fr = [e]
    while fr:
        nx = []
        for x in fr:
            for g in gens:
                y = mul(x, g)
                if y not in seen:
                    seen.add(y); nx.append(y)
        fr = nx
    return Group(name, sorted(seen), mul, e)


def central_quotient(G, z, name):
    """G / <z> for a central element z of order 2."""
    cos = {}
    reps = []
    for g in G.elements:
        if g in cos:
            continue
        r = len(reps); reps.append(g)
        cos[g] = r; cos[G.mul(g, z)] = r
    els = list(range(len(reps)))
    def mul(i, j):
        return cos[G.mul(reps[i], reps[j])]
    return Group(name, els, mul, cos[G.e])


def z4_semi_z4():
    """Z/4 rtimes Z/4, the action being inversion. SmallGroup(16,4)."""
    els = [(a, b) for a in range(4) for b in range(4)]
    def mul(p, q):
        s = 1 if p[1] % 2 == 0 else -1
        return ((p[0] + s * q[0]) % 4, (p[1] + q[1]) % 4)
    return Group("Z/4:Z/4", els, mul, (0, 0))


def klein_semi_z4():
    """(Z/2)^2 rtimes Z/4, the generator of Z/4 swapping the two factors.
    SmallGroup(16,3)."""
    els = [((x, y), c) for x in range(2) for y in range(2) for c in range(4)]
    def mul(p, q):
        (x1, y1), c1 = p; (x2, y2), c2 = q
        if c1 % 2 == 1:
            x2, y2 = y2, x2
        return (((x1 + x2) % 2, (y1 + y2) % 2), (c1 + c2) % 4)
    return Group("(Z/2)^2:Z/4", els, mul, ((0, 0), 0))


def sl2f3():
    els = []
    for a, b, c, d in product(range(3), repeat=4):
        if (a * d - b * c) % 3 == 1:
            els.append((a, b, c, d))
    def mul(p, q):
        a1, b1, c1, d1 = p; a2, b2, c2, d2 = q
        return ((a1 * a2 + b1 * c2) % 3, (a1 * b2 + b1 * d2) % 3,
                (c1 * a2 + d1 * c2) % 3, (c1 * b2 + d1 * d2) % 3)
    return Group("SL_2(F_3)", els, mul, (1, 0, 0, 1))


def catalogue():
    """The 25 nonabelian groups of order less than 24, in order of size."""
    out = []
    out.append(dihedral(3))                                   # order 6
    out.append(dihedral(4)); out.append(quaternion8())        # order 8
    out.append(dihedral(5))                                   # order 10
    A4 = perm_group("A_4", [(1, 2, 0, 3), (0, 2, 3, 1)], 4)
    out.append(A4)
    out.append(dihedral(6)); out.append(dicyclic(3))          # order 12
    out.append(dihedral(7))                                   # order 14
    # the nine nonabelian groups of order 16
    out.append(dihedral(8))
    out.append(dicyclic(4))
    out.append(semidirect(8, 2, lambda b: 1 if b == 0 else 3, "SD_16"))
    out.append(semidirect(8, 2, lambda b: 1 if b == 0 else 5, "M_16"))
    out.append(direct(dihedral(4), cyclic(2), "D_4 x Z/2"))
    out.append(direct(quaternion8(), cyclic(2), "Q_8 x Z/2"))
    out.append(z4_semi_z4())
    out.append(klein_semi_z4())
    D4Z4 = direct(dihedral(4), cyclic(4), "D_4 x Z/4")
    z = ((2, 0), 2)          # (central involution of D_4, the element 2 of Z/4)
    out.append(central_quotient(D4Z4, z, "D_4 o Z/4"))
    # order 18
    out.append(dihedral(9))
    out.append(direct(dihedral(3), cyclic(3), "S_3 x Z/3"))
    E9 = direct(cyclic(3), cyclic(3), "(Z/3)^2")
    els = [(v, b) for v in E9.elements for b in range(2)]
    def mul18(p, q):
        v1, b1 = p; v2, b2 = q
        s = 1 if b1 == 0 else -1
        return (((v1[0] + s * v2[0]) % 3, (v1[1] + s * v2[1]) % 3), (b1 + b2) % 2)
    out.append(Group("(Z/3)^2:Z/2", els, mul18, ((0, 0), 0)))
    # order 20
    out.append(dihedral(10))
    out.append(dicyclic(5))
    out.append(semidirect(5, 4, lambda b: pow(2, b, 5), "F_20"))
    # order 21, 22
    out.append(semidirect(7, 3, lambda b: pow(2, b, 7), "F_21"))
    out.append(dihedral(11))
    return out


def controls():
    S4 = perm_group("S_4", [(1, 2, 3, 0), (1, 0, 2, 3)], 4)
    return [S4, sl2f3()]


# ---------------------------------------------------------------- checks

def isomorphic(G, H):
    if len(G) != len(H):
        return False
    from collections import Counter
    if (Counter(G.order_of(g) for g in G.elements)
            != Counter(H.order_of(h) for h in H.elements)):
        return False
    gens = minimal_generators(G)
    cand = [[h for h in H.elements if H.order_of(h) == G.order_of(g)]
            for g in gens]
    for images in product(*cand):
        if extend_hom(G, H, gens, images) is not None:
            return True
    return False


def minimal_generators(G):
    els = G.elements
    for k in (1, 2, 3, 4):
        for tup in product(els, repeat=k):
            if len(G.closure(tup)) == len(G):
                return list(tup)
    raise RuntimeError("no small generating set")


def extend_hom(G, H, gens, images):
    """The homomorphism G -> H sending gens to images, or None."""
    f = {G.e: H.e}
    fr = [G.e]
    while fr:
        nx = []
        for x in fr:
            for g, im in zip(gens, images):
                y = G.mul(x, g); fy = H.mul(f[x], im)
                if y in f:
                    if f[y] != fy:
                        return None
                elif True:
                    f[y] = fy; nx.append(y)
        fr = nx
    if len(f) != len(G) or len(set(f.values())) != len(H):
        return None
    for a in G.elements:
        for b in G.elements:
            if f[G.mul(a, b)] != H.mul(f[a], f[b]):
                return None
    return f


def check_catalogue():
    """Order, nonabelianness, and pairwise non-isomorphism within each order.
    The counts are compared with the classification of groups of small order."""
    cat = catalogue()
    by_order = {}
    for G in cat:
        by_order.setdefault(len(G), []).append(G)
    expected = {6: 1, 8: 2, 10: 1, 12: 3, 14: 1, 16: 9, 18: 3, 20: 3, 21: 1, 22: 1}
    report = []
    ok = True
    for n in sorted(by_order):
        gs = by_order[n]
        if len(gs) != expected[n]:
            ok = False
        for G in gs:
            if len(G) != n or G.is_abelian():
                ok = False
        for i in range(len(gs)):
            for j in range(i + 1, len(gs)):
                if isomorphic(gs[i], gs[j]):
                    ok = False
                    report.append("isomorphic: %s and %s" % (gs[i].name, gs[j].name))
        report.append("order %2d: %d nonabelian groups, expected %d"
                      % (n, len(gs), expected[n]))
    return ok, report


if __name__ == "__main__":
    ok, report = check_catalogue()
    for line in report:
        print(line)
    print("total:", len(catalogue()), "nonabelian groups of order below 24")
    print("catalogue check:", "passed" if ok else "FAILED")
