def chen_table_data(G, X, idx, rep, perms):
    """Orbit of SL_2(Z) = <R, L> on Epi(F_2,G)/Inn(G), the action of -I, the
    cusp widths (cycle lengths of R on the orbit modulo -I), and e = order of
    rho([a,b])."""
    surj = [i for i, (x, y) in enumerate(X) if len(G.closure((x, y))) == len(G)]
    R, L = perms["R"], perms["L"]
    orbits = []; seen = set()
    for s in surj:
        if s in seen: continue
        O = {s}; dq = [s]
        while dq:
            t = dq.pop()
            for p in (R, L, pinv(R), pinv(L)):
                u = p[t]
                if u not in O: O.add(u); dq.append(u)
        seen |= O; orbits.append(sorted(O))
    # -I = (R L^-1 R)^2 ... use E^2? no: -I = (R L^{-1} R)^2 in SL_2(Z)
    S = pmul(R, pmul(pinv(L), R)); minusI = pmul(S, S)
    out = []
    for O in orbits:
        free = all(minusI[t] != t for t in O)
        # cusp widths: cycles of R on O / <-I>
        cls = {}
        for t in O:
            cls[t] = min(t, minusI[t])
        pts = sorted(set(cls.values()))
        done = set(); widths = []
        for t in pts:
            if t in done: continue
            k = 0; u = t
            while u not in done:
                done.add(u); k += 1; u = cls[R[u]]
            widths.append(k)
        x, y = X[O[0]]
        comm = G.mul(G.mul(x, y), G.mul(G.inv(x), G.inv(y)))
        out.append((len(O), free, Counter(widths), G.order_of(comm)))
    return out

