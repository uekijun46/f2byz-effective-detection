"""Verification of prop:order54: the group G = (Z/3)^2 : Q_8, numbered (72,41)
in the small groups library, is congruence of level 12, and the group (48,33)
is not congruence.

Congruence is taken in the sense of def:level: the action of GL_2(Z) on
X_G = Hom(F_2,G)/Inn(G) extends to an action of GL_2(Z/N), compatibly with
Aut(G). The image of GL_2(Z) in GL_2(Z/N) is only the subgroup P of
determinant +-1, so two things are checked for G = (72,41) and N = 12.

(1) Gamma(12) acts trivially on X_G. The subgroup D of SL_2(Z/12) x Sym(X_G)
    generated by the pairs (R mod 12, sigma(R)) and (L mod 12, sigma(L)) has
    order 1152 = |SL_2(Z/12)|, so its projection to SL_2(Z/12) is injective.
    Since Gamma(12) is normal in GL_2(Z), the action of GL_2(Z) then factors
    through P. The same count gives 31104 for S_4 and 73728 for SL_2(F_3),
    against 1152, and 144 = |SL_2(Z/6)| for S_3.

(2) The action of P extends to GL_2(Z/12) = P u P.delta, delta = diag(1,5),
    compatibly with Aut(G). Let K be the group generated by P and Aut(G) in
    Sym(X_G). An extension is a permutation tau of X_G with tau^2 = 1,
    tau sigma(h) tau = sigma(delta h delta) for h in P, and tau alpha = alpha tau
    for alpha in Aut(G); it is found orbit by orbit. On a K-orbit O with base
    point x, a candidate tau is determined by y = tau(x), which must satisfy
    delta Stab(y) delta = Stab(x) (stabilizers in P, with Aut(G) fixed), and
    then tau(k.x) = theta(k).y where theta is the twist of K by delta. The
    candidate is accepted when it is an involution. Orbits with no accepted
    candidate could still be swapped in pairs; here every orbit accepts one.

The group (48,33) is C_4 o SL_2(F_3), the central product. It has only
metabelian proper quotients, and the script certifies that it is not
congruence by exhibiting a matrix in Gamma(24) that acts nontrivially on
X_G. By the theorem of Wohlfahrt, in the form of Kiming, Schuett, and
Verrill, a subgroup of finite index of geometric level l is congruence if and
only if it contains Gamma(2l); the geometric level of the kernel is the order
of sigma(R), which is 12, so Gamma(24) is the group to test. The identification
of the construction with (48,33) is checked against Table 4 of Chen,
Math. Ann. 371 (2018): one SL_2(Z)-orbit on Epi(F_2,G)/Inn(G), of size 96,
on which -I acts freely, with cusp widths 2^4 3^2 4 6 12^2 and e = 4.

Usage:  python3 order72_check.py
"""
