# ---------------------------------------------------------------- matrices mod N

def mmul(A, B, N):
    a, b, c, d = A; e, f, g, h = B
    return ((a*e + b*g) % N, (a*f + b*h) % N, (c*e + d*g) % N, (c*f + d*h) % N)

def det(M, N):
    a, b, c, d = M
    return (a*d - b*c) % N

def minv(M, N):
    a, b, c, d = M
    di = pow(det(M, N), -1, N)
    return ((d*di) % N, (-b*di) % N, (-c*di) % N, (a*di) % N)

def sl2_order(N):
    from math import gcd
    n = N; out = 1; p = 2
    while n > 1:
        if n % p == 0:
            k = 0
            while n % p == 0:
                n //= p; k += 1
            out *= p**(3*k) * (1 - 1/(p*p))
        p += 1
    return round(out)


# ---------------------------------------------------------------- the groups

def m2(A, B, p):
    a, b, c, d = A; e, f, g, h = B
    return ((a*e + b*g) % p, (a*f + b*h) % p, (c*e + d*g) % p, (c*f + d*h) % p)

def group_72_41():
    """(Z/3)^2 : Q_8, with Q_8 <= SL_2(F_3) acting by its natural representation.
    Elements (v, q), v in F_3^2, q in Q_8 as a 2x2 matrix mod 3."""
    S = sl2f3()
    i = (0, 1, 2, 0); j = (1, 1, 1, 2)
    Q8 = sorted(S.closure((i, j)))
    assert len(Q8) == 8
    els = [((v0, v1), q) for v0 in range(3) for v1 in range(3) for q in Q8]
    def mul(x, y):
        (v, q), (w, r) = x, y
        qw = ((q[0]*w[0] + q[1]*w[1]) % 3, (q[2]*w[0] + q[3]*w[1]) % 3)
        return (((v[0] + qw[0]) % 3, (v[1] + qw[1]) % 3), m2(q, r, 3))
    return Group("(72,41)", els, mul, ((0, 0), (1, 0, 0, 1)))

def group_48_33():
    """C_4 o SL_2(F_3) = (C_4 x SL_2(F_3)) / <(2, -I)>.  Elements (k, M) with
    k in Z/4, normalized so that M is the smaller of M and -M."""
    S = sl2f3()
    def neg(M): return tuple((-x) % 3 for x in M)
    def norm(k, M):
        return (k, M) if M <= neg(M) else ((k + 2) % 4, neg(M))
    els = sorted({norm(k, M) for k in range(4) for M in S.elements})
    def mul(x, y):
        return norm((x[0] + y[0]) % 4, m2(x[1], y[1], 3))
    e = norm(0, (1, 0, 0, 1))
    return Group("(48,33)", els, mul, e)


# ---------------------------------------------------------------- group invariants

def commutator_subgroup(G, H):
    gens = {G.mul(G.mul(a, b), G.mul(G.inv(a), G.inv(b))) for a in H for b in H}
    return G.closure(gens)

def derived_length(G):
    H = set(G.elements); k = 0
    while len(H) > 1:
        H = commutator_subgroup(G, H); k += 1
    return k

def center(G):
    return [z for z in G.elements if all(G.mul(z, g) == G.mul(g, z) for g in G.elements)]

def normal_subgroups(G):
    """All normal subgroups, as frozensets, by closing unions of conjugacy classes."""
    classes = []; seen = set()
    for g in G.elements:
        if g in seen: continue
        c = frozenset(G.mul(G.mul(h, g), G.inv(h)) for h in G.elements)
        seen |= c; classes.append(c)
    out = set()
    for mask in range(1 << len(classes)):
        S = set()
        for i, c in enumerate(classes):
            if mask >> i & 1: S |= c
        if G.e not in S: continue
        if G.closure(S) == S: out.add(frozenset(S))
    return out

def two_generated(G):
    return any(len(G.closure((a, b))) == len(G) for a in G.elements for b in G.elements)


# ---------------------------------------------------------------- levels and the Nielsen action

def level_XG(G):
    """X_G = Hom(F_2,G)/Inn(G) with the left action of the Nielsen generators.
    phi_R: a -> a, b -> ab;  phi_L: a -> ab, b -> b;  phi_E: a -> a, b -> b^-1.
    The left action is rho -> rho o phi^-1, so on pairs (x,y) = (rho(a), rho(b)):
    R: (x,y) -> (x, x^-1 y),  L: (x,y) -> (x y^-1, y),  E: (x,y) -> (x, y^-1).
    Their matrices are R = (1 1; 0 1), L = (1 0; 1 1), E = diag(1,-1)."""
    inv = {g: G.inv(g) for g in G.elements}
    rep = {}
    for x in G.elements:
        for y in G.elements:
            if (x, y) in rep: continue
            orb = {(G.mul(G.mul(g, x), inv[g]), G.mul(G.mul(g, y), inv[g])) for g in G.elements}
            r = min(orb)
            for q in orb: rep[q] = r
    X = sorted(set(rep.values())); idx = {r: i for i, r in enumerate(X)}
    def perm(f): return tuple(idx[rep[f(x, y)]] for (x, y) in X)
    pR = perm(lambda x, y: (x, G.mul(inv[x], y)))
    pL = perm(lambda x, y: (G.mul(x, inv[y]), y))
    pE = perm(lambda x, y: (x, inv[y]))
    return X, idx, rep, {"R": pR, "L": pL, "E": pE}

MAT = {"R": (1, 1, 0, 1), "L": (1, 0, 1, 1), "E": (1, 0, 0, -1)}

def pmul(p, q): return tuple(p[q[i]] for i in range(len(q)))
def pinv(p):
    r = [0]*len(p)
    for i, j in enumerate(p): r[j] = i
    return tuple(r)

def image_group(N, perms, names):
    """The subgroup of GL_2(Z/N) x Sym(X) generated by (MAT[g] mod N, perms[g]),
    as a dict matrix -> permutation.  Raises if the projection is not injective."""
    I = (1, 0, 0, 1); e = tuple(range(len(next(iter(perms.values())))))
    gens = [(tuple(v % N for v in MAT[g]), perms[g]) for g in names]
    seen = {I: e}; dq = deque([(I, e)]); conflict = None
    while dq:
        M, P = dq.popleft()
        for Mg, Pg in gens:
            M2 = mmul(Mg, M, N); P2 = pmul(Pg, P)
            if M2 in seen:
                if seen[M2] != P2: conflict = (M2, seen[M2], P2)
            else:
                seen[M2] = P2; dq.append((M2, P2))
    return seen, conflict

def image_order(N, perms, names):
    """Order of the subgroup generated by the pairs, computed without the
    injectivity assumption (pairs are the elements)."""
    I = (1, 0, 0, 1); e = tuple(range(len(next(iter(perms.values())))))
    gens = [(tuple(v % N for v in MAT[g]), perms[g]) for g in names]
    seen = {(I, e)}; dq = deque([(I, e)])
    while dq:
        M, P = dq.popleft()
        for Mg, Pg in gens:
            x = (mmul(Mg, M, N), pmul(Pg, P))
            if x not in seen:
                seen.add(x); dq.append(x)
    return len(seen)


# ---------------------------------------------------------------- Aut(G) on X_G

def automorphisms(G):
    gens = minimal_generators(G)
    orders = [G.order_of(g) for g in gens]
    cand = [[h for h in G.elements if G.order_of(h) == o] for o in orders]
    auts = []
    for images in product(*cand):
        f = extend_hom(G, G, gens, images)
        if f is not None: auts.append(f)
    return auts

def aut_perms(G, X, idx, rep):
    out = set()
    for f in automorphisms(G):
        out.add(tuple(idx[rep[(f[x], f[y])]] for (x, y) in X))
    return sorted(out)


# ---------------------------------------------------------------- the extension test

def extension_test(N, sigma, delta, autperms):
    """sigma: dict P -> Sym(X) (P = matrices of determinant +-1 mod N, a
    homomorphism).  delta: a matrix with delta^2 = I and det delta not +-1,
    with GL_2(Z/N) = P u P.delta.  autperms: the permutations of Aut(G).
    Returns (ok, list of orbit sizes, number of orbits with a candidate)."""
    assert mmul(delta, delta, N) == (1, 0, 0, 1)
    dinv = minv(delta, N)
    P = list(sigma); n = len(next(iter(sigma.values())))
    K = [(M, a) for M in P for a in autperms]
    act = {k: pmul(sigma[k[0]], k[1]) for k in K}
    theta = {k: (mmul(mmul(delta, k[0], N), dinv, N), k[1]) for k in K}
    assert all(theta[k][0] in sigma for k in K)
    orbit_of = [-1]*n; orbits = []
    for x in range(n):
        if orbit_of[x] >= 0: continue
        O = sorted({act[k][x] for k in K})
        for y in O: orbit_of[y] = len(orbits)
        orbits.append(O)
    stab = {}
    def Stab(x):
        if x not in stab: stab[x] = frozenset(k for k in K if act[k][x] == x)
        return stab[x]
    fixed = 0; tau_all = {}
    for O in orbits:
        x = O[0]; Sx = Stab(x); found = False
        for y in O:
            if frozenset(theta[k] for k in Stab(y)) != Sx: continue
            tau = {}; ok = True
            for k in K:
                a = act[k][x]; b = act[theta[k]][y]
                if a in tau and tau[a] != b: ok = False; break
                tau[a] = b
            if ok and all(tau[tau[a]] == a for a in O):
                tau_all.update(tau); found = True; break
        if found: fixed += 1
    ok = fixed == len(orbits)
    if ok:   # verify the assembled tau directly
        tau = tuple(tau_all[i] for i in range(n))
        assert pmul(tau, tau) == tuple(range(n))
        for M in P:
            assert pmul(pmul(tau, sigma[M]), tau) == sigma[mmul(mmul(delta, M, N), dinv, N)]
        for a in autperms:
            assert pmul(tau, a) == pmul(a, tau)
    return ok, [len(O) for O in orbits], fixed


# ---------------------------------------------------------------- Gamma(2l) certificate

def gamma_certificate(N, perms, trials=200000, seed=1):
    """A word in R, L, E whose matrix is the identity mod N and whose
    permutation is not the identity, found by collision of random words.
    Returns (integer matrix, number of moved points, word) or None."""
    rnd = random.Random(seed)
    names = ["R", "L", "E"]
    inv = {g: pinv(perms[g]) for g in names}
    Z = {"R": (1, 1, 0, 1), "L": (1, 0, 1, 1), "E": (1, 0, 0, -1)}
    def zmul(A, B):
        a, b, c, d = A; e, f, g, h = B
        return (a*e + b*g, a*f + b*h, c*e + d*g, c*f + d*h)
    seen = {}
    n = len(perms["R"])
    for _ in range(trials):
        w = [rnd.choice(names) for _ in range(rnd.randint(8, 40))]
        M = (1, 0, 0, 1); P = tuple(range(n))
        for g in w:
            M = zmul(Z[g], M); P = pmul(perms[g], P)
        key = tuple(v % N for v in M)
        if key in seen:
            M0, P0, w0 = seen[key]
            if P0 != P:
                # g = M0^-1 M  is in Gamma(N) (M0 and M agree mod N); its action is P0^-1 P
                a, b, c, d = M0; dd = a*d - b*c            # +-1
                M0inv = (d*dd, -b*dd, -c*dd, a*dd)
                g = zmul(M0inv, M)
                Pg = pmul(pinv(P0), P)
                moved = sum(1 for i in range(n) if Pg[i] != i)
                assert all(v % N == (1 if i in (0, 3) else 0) for i, v in enumerate(g))
                return g, moved, (w0, w)
        else:
            seen[key] = (M, P, w)
    return None


