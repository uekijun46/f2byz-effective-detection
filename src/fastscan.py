#!/usr/bin/env python3
"""fastscan.py -- large-T exhaustive scan.

Two rewrites of the bottleneck:
 (1) class enumeration: instead of enumerating divisors (O(D) per T), build the
     narrow class group by BFS from prime forms using Gaussian composition.
     Cost ~ h(D) per T instead of ~D.
 (2) cycle types: numpy-vectorised Vieta permutation on F_q^3.

Both are validated against markoff_rigidity (classes / cycle_type_on_Fq).
"""
import sys
from math import isqrt, gcd
import numpy as np
from markoff_rigidity import canon, automorph, decomp, _is_reduced, _rho

# ---------------------------------------------------------------- forms
def reduce_form(f, D):
    g = f
    guard = 0
    while not _is_reduced(g, D):
        g = _rho(g, D); guard += 1
        if guard > 10000: raise RuntimeError('reduction loop')
    return g

def compose(f1, f2, D):
    """Gaussian composition of two forms of discriminant D (Cohen 5.4.7)."""
    a1, b1, c1 = f1; a2, b2, c2 = f2
    if a1 > a2:
        a1, b1, c1, a2, b2, c2 = a2, b2, c2, a1, b1, c1
    s = (b1 + b2) // 2
    n = b2 - s
    if a2 % a1 == 0:
        y1, d = 0, a1
    else:
        d, u, v = ext_gcd(a2, a1)      # u*a2 + v*a1 = d
        y1 = u
    if s % d == 0:
        y2, x2, d1 = -1, 0, d
    else:
        d1, u, v = ext_gcd(s, d)
        x2, y2 = u, -v
    v1 = a1 // d1; v2 = a2 // d1
    r = (y1 * y2 * n - x2 * c2) % v1
    b3 = b2 + 2 * v2 * r
    a3 = v1 * v2
    c3 = (b3 * b3 - D) // (4 * a3)
    return reduce_form((a3, b3, c3), D)

def ext_gcd(a, b):
    if b == 0: return (a, 1, 0)
    g, x, y = ext_gcd(b, a % b)
    return (g, y, x - (a // b) * y)

def sqrt_mod_p(a, p):
    a %= p
    if a == 0: return 0
    if pow(a, (p - 1) // 2, p) != 1: return None
    if p % 4 == 3: return pow(a, (p + 1) // 4, p)
    q, s = p - 1, 0
    while q % 2 == 0: q //= 2; s += 1
    z = 2
    while pow(z, (p - 1) // 2, p) != p - 1: z += 1
    m, c, t, r = s, pow(z, q, p), pow(a, q, p), pow(a, (q + 1) // 2, p)
    while t != 1:
        i, t2 = 0, t
        while t2 != 1: t2 = t2 * t2 % p; i += 1
        b = pow(c, 1 << (m - i - 1), p)
        m, c = i, b * b % p
        t = t * c % p; r = r * b % p
    return r

_PRIMES = None
def primes_up(n):
    global _PRIMES
    if _PRIMES is None or _PRIMES[-1] < n:
        sieve = bytearray([1]) * (n + 1); sieve[0:2] = b'\x00\x00'
        for i in range(2, isqrt(n) + 1):
            if sieve[i]: sieve[i*i::i] = bytearray(len(sieve[i*i::i]))
        _PRIMES = [i for i in range(n + 1) if sieve[i]]
    return [p for p in _PRIMES if p <= n]

def principal_form(D):
    b = D % 2
    return reduce_form((1, b, (b * b - D) // 4), D)

def class_reps(D, pbound=3000):
    """Narrow class group as canonical reps, via BFS from prime forms."""
    pr = canon(principal_form(D), D)
    # the narrow class group can be twice the group generated by forms with a>0;
    # the class of the NEGATIVE principal form bridges that index-2 gap.
    b0 = D % 2
    gens = [reduce_form((-1, b0, (D - b0 * b0) // 4), D)]
    for p in primes_up(pbound):
        if D % p == 0: continue
        r = sqrt_mod_p(D, p)
        if r is None: continue
        for b0 in (r, p - r):
            b = b0 if (b0 - D) % 2 == 0 else b0 + p
            if (b * b - D) % (4 * p): continue
            f = reduce_form((p, b, (b * b - D) // (4 * p)), D)
            gens.append(f)
        if len(gens) >= 200: break
    # coset construction: total number of compositions is O(h), not h*|gens|
    forms = [principal_form(D)]; seen = {pr}
    idle = 0
    for g in gens:
        if canon(g, D) in seen:
            idle += 1
            if idle >= 40: break
            continue
        idle = 0
        base = list(forms)
        cur = g
        while canon(cur, D) not in seen:
            for f in base:
                h = compose(f, cur, D)
                k = canon(h, D)
                if k not in seen:
                    seen.add(k); forms.append(h)
            cur = compose(cur, g, D)
    return sorted(seen)

# ---------------------------------------------------------------- cycle types
_TAB = {}
def _tab(q):
    if q not in _TAB:
        idx = np.arange(q**3)
        x = idx // (q * q); y = (idx // q) % q; z = idx % q
        _TAB[q] = (x, y, z)
    return _TAB[q]

def _apply(g, x, y, z, q):
    if g == 'T':  return x, z, (x * z - y) % q
    if g == 'Ti': return x, (x * y - z) % q, y
    if g in ('S', 'Si'): return y, x, (x * y - z) % q
    return x, y, (x * y - z) % q

_LET = {}
def _letters_np(q):
    if q not in _LET:
        x, y, z = _tab(q)
        d = {}
        for g in ('T','Ti','S','J'):
            a, b, c = _apply(g, x, y, z, q)
            d[g] = ((a * q + b) * q + c).astype(np.int32)
        d['Si'] = d['S']
        _LET[q] = d
    return _LET[q]

def cycle_type_np(word, q):
    L = _letters_np(q)
    p = np.arange(q ** 3, dtype=np.int32)
    for g in word:
        p = L[g][p]
    n = q ** 3
    pl = p.tolist(); sn = bytearray(n)
    from collections import Counter
    ct = Counter()
    for s in range(n):
        if sn[s]: continue
        Lc = 0; t = s
        while not sn[t]:
            sn[t] = 1; Lc += 1; t = pl[t]
        ct[Lc] += 1
    return tuple(sorted(ct.items()))

